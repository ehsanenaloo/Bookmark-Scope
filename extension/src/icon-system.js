export function iconSvg(kind) {
  return ICON_SVGS[kind] || ICON_SVGS.settings;
}

export function createIconElement(kind, classes = 'icon-svg') {
  const wrap = document.createElement('span');
  if (classes) wrap.className = classes;
  wrap.setAttribute('aria-hidden', 'true');
  wrap.innerHTML = iconSvg(kind);
  return wrap;
}

export function createIconButton(kind, title, classes = 'icon-button mono-icon-button') {
  const button = document.createElement('button');
  if (classes) button.className = classes;
  button.type = 'button';
  if (title) {
    button.title = title;
    button.setAttribute('aria-label', title);
  }
  button.innerHTML = iconSvg(kind);
  return button;
}
